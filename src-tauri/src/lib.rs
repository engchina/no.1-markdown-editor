#[tauri::command]
async fn create_browser_webview<R: tauri::Runtime>(
    app: tauri::AppHandle<R>,
    label: String,
    url: String,
    x: f64,
    y: f64,
    width: f64,
    height: f64,
) -> Result<(), String> {
    append_log(&format!(
        "create_browser_webview: label={}, url={}, x={}, y={}, w={}, h={}",
        label, url, x, y, width, height
    ));
    let main_window = app
        .get_window("main")
        .ok_or_else(|| "Main window not found".to_string())?;

    if let Some(webview) = app.get_webview(&label) {
        append_log("webview already exists, repositioning and showing");
        let (tx, rx) = tokio::sync::oneshot::channel();
        let _ = app.run_on_main_thread(move || {
            let res = (|| -> Result<(), String> {
                let _ = webview.set_position(Position::Logical(LogicalPosition::new(x, y)));
                let _ = webview.set_size(Size::Logical(LogicalSize::new(width, height)));
                let _ = webview.show();
                let _ = webview.set_focus();
                Ok(())
            })();
            let _ = tx.send(res);
        });
        return rx.await.map_err(|e| format!("Channel error: {e}"))?;
    }

    append_log("creating new child webview");
    let webview_url = WebviewUrl::External(url.parse().map_err(|error| {
        let err_msg = format!("Invalid URL: {error}");
        append_log(&err_msg);
        err_msg
    })?);
    let label_clone = label.clone();
    let app_handle = app.clone();
    let app_handle_title = app.clone();
    let webview_builder = WebviewBuilder::new(&label, webview_url)
        .zoom_hotkeys_enabled(true)
        .initialization_script(BROWSER_BRIDGE_SCRIPT)
        .on_page_load(move |_webview, payload| {
            if let tauri::webview::PageLoadEvent::Finished = payload.event() {
                let url_str = payload.url().to_string();
                let _ = app_handle.emit(&format!("browser-url-changed-{}", label_clone), url_str);
            }
        })
        .on_document_title_changed(move |webview, title| {
            handle_browser_title_report(&app_handle_title, webview.label(), &title);
        });

    let (tx, rx) = tokio::sync::oneshot::channel();
    let _ = app.run_on_main_thread(move || {
        let res = (|| -> Result<(), String> {
            let child = main_window
                .add_child(
                    webview_builder,
                    LogicalPosition::new(x, y),
                    LogicalSize::new(width, height),
                )
                .map_err(|error| {
                    let err_msg = format!("Failed to create child webview: {error}");
                    append_log(&err_msg);
                    err_msg
                })?;

            let _ = child.show();
            let _ = child.set_focus();
            append_log("new child webview created and shown successfully");
            Ok(())
        })();
        let _ = tx.send(res);
    });

    rx.await.map_err(|e| format!("Channel error: {e}"))?
}

