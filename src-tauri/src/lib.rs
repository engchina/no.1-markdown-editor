fn is_windows_key_down(vk: windows::Win32::UI::Input::KeyboardAndMouse::VIRTUAL_KEY) -> bool {
    use windows::Win32::UI::Input::KeyboardAndMouse::GetKeyState;

    unsafe { GetKeyState(vk.0 as i32) < 0 }
}

#[cfg(target_os = "windows")]
fn resolve_browser_accelerator_shortcut(
    virtual_key: u32,
    ctrl: bool,
    shift: bool,
    alt: bool,
) -> Option<&'static str> {
    use windows::Win32::UI::Input::KeyboardAndMouse::{
        VK_0, VK_A, VK_ADD, VK_F11, VK_H, VK_J, VK_N, VK_NUMPAD0, VK_O, VK_OEM_2, VK_OEM_5,
        VK_OEM_COMMA, VK_OEM_MINUS, VK_OEM_PLUS, VK_P, VK_S, VK_SUBTRACT, VK_T, VK_W,
    };

    if alt {
        return (virtual_key == VK_A.0 as u32 && !ctrl && !shift)
            .then_some("edit.captureScreenshot");
    }

    if virtual_key == VK_F11.0 as u32 && !ctrl && !shift {
        return Some("view.toggleFocus");
    }

    if !ctrl {
        return None;
    }

    match virtual_key {
        key if key == VK_N.0 as u32 && !shift => Some("file.new"),
        key if key == VK_O.0 as u32 && !shift => Some("file.open"),
        key if key == VK_S.0 as u32 && !shift => Some("file.save"),
        key if key == VK_S.0 as u32 && shift => Some("file.saveAs"),
        key if key == VK_W.0 as u32 && !shift => Some("file.close"),
        key if key == VK_T.0 as u32 && !shift => Some("browser.new"),
        key if key == VK_P.0 as u32 && !shift => Some("file.switchOpen"),
        key if key == VK_P.0 as u32 && shift => Some("view.commandPalette"),
        key if key == VK_J.0 as u32 && !shift => Some("ai.open"),
        key if key == VK_J.0 as u32 && shift => Some("ai.setup"),
        key if key == VK_H.0 as u32 && shift => Some("edit.imageHosting"),
        key if key == VK_OEM_2.0 as u32 && !shift => Some("help.keyboardShortcuts"),
        key if key == VK_OEM_5.0 as u32 && !shift => Some("view.toggleSidebar"),
        key if key == VK_OEM_COMMA.0 as u32 && !shift => Some("view.appearance"),
        key if key == VK_OEM_PLUS.0 as u32 || key == VK_ADD.0 as u32 => Some("view.zoomIn"),
        key if key == VK_OEM_MINUS.0 as u32 || key == VK_SUBTRACT.0 as u32 => Some("view.zoomOut"),
        key if key == VK_0.0 as u32 || key == VK_NUMPAD0.0 as u32 => Some("view.zoomReset"),
        _ => None,
    }
}

#[cfg(target_os = "windows")]
fn attach_browser_shortcut_handler<R: tauri::Runtime>(
    app: tauri::AppHandle<R>,
    webview: &tauri::Webview<R>,
) -> Result<(), String> {
    use webview2_com::AcceleratorKeyPressedEventHandler;
    use webview2_com::Microsoft::Web::WebView2::Win32::{
        COREWEBVIEW2_KEY_EVENT_KIND_KEY_DOWN, COREWEBVIEW2_KEY_EVENT_KIND_SYSTEM_KEY_DOWN,
    };
    use windows::Win32::UI::Input::KeyboardAndMouse::{VK_CONTROL, VK_MENU, VK_SHIFT};

    let (tx, rx) = std::sync::mpsc::channel();

    webview
        .with_webview(move |platform_webview| {
            let result = (|| -> Result<(), String> {
                let controller = platform_webview.controller();
                let app_handle = app.clone();
                let mut token = 0i64;

                unsafe {
                    controller
                        .add_AcceleratorKeyPressed(
                            &AcceleratorKeyPressedEventHandler::create(Box::new(
                                move |_controller, args| {
                                    let Some(args) = args else {
                                        return Ok(());
                                    };

                                    let mut event_kind = Default::default();
                                    args.KeyEventKind(&mut event_kind)?;
                                    if event_kind != COREWEBVIEW2_KEY_EVENT_KIND_KEY_DOWN
                                        && event_kind != COREWEBVIEW2_KEY_EVENT_KIND_SYSTEM_KEY_DOWN
                                    {
                                        return Ok(());
                                    }

                                    let mut virtual_key = 0u32;
                                    args.VirtualKey(&mut virtual_key)?;

                                    let ctrl = is_windows_key_down(VK_CONTROL);
                                    let shift = is_windows_key_down(VK_SHIFT);
                                    let alt = is_windows_key_down(VK_MENU);
                                    let Some(command) = resolve_browser_accelerator_shortcut(
                                        virtual_key,
                                        ctrl,
                                        shift,
                                        alt,
                                    ) else {
                                        return Ok(());
                                    };

                                    let mut physical_status = Default::default();
                                    args.PhysicalKeyStatus(&mut physical_status)?;
                                    args.SetHandled(true)?;

                                    let _ = app_handle.emit(
                                        APP_BROWSER_SHORTCUT_EVENT,
                                        BrowserShortcutPayload {
                                            command,
                                            repeat: physical_status.WasKeyDown.as_bool(),
                                        },
                                    );
                                    Ok(())
                                },
                            )),
                            &mut token,
                        )
                        .map_err(|error| error.to_string())?;
                }

                Ok(())
            })();
            let _ = tx.send(result);
        })
        .map_err(|error| format!("Failed to attach browser shortcut handler: {error}"))?;

    rx.recv()
        .map_err(|error| format!("Failed to receive browser shortcut setup result: {error}"))?
}

