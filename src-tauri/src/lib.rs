/// Title-channel reassembly buffers, keyed by requestId. Used as the
/// cross-platform fallback when the external webview cannot reach the Tauri IPC
/// (`browser_report_content`) directly — the bridge then streams the base64
/// payload through `document.title` in chunks.
const MAX_BROWSER_TITLE_CHANNEL_CHUNKS: usize = 512;
const MAX_BROWSER_TITLE_CHANNEL_CHUNK_CHARS: usize = 4096;

#[derive(Default)]
struct BrowserTitleChannels(Mutex<BrowserTitleChannelState>);

#[derive(Default)]
struct BrowserTitleChannelState {
    pending: HashSet<String>,
    buffers: HashMap<String, TitleChannelBuffer>,
}

struct TitleChannelBuffer {
    total: usize,
    chunks: BTreeMap<usize, String>,
}

/// Payload emitted to the frontend on `browser-agent-data-{label}` once a full
/// page snapshot has been received (via either channel). `payload` is the JSON
/// string produced by the bridge's `buildSnapshot()`.
#[derive(Clone, serde::Serialize)]
#[serde(rename_all = "camelCase")]
struct BrowserAgentData {
    request_id: String,
    payload: String,
}

#[derive(Clone, serde::Serialize)]
#[serde(rename_all = "camelCase")]
struct BrowserShortcutPayload {
    command: &'static str,
    repeat: bool,
}

/// requestIds are generated by the frontend and embedded into an `eval` string;
/// restrict them to an alphanumeric allow-list so they can never break out of
/// the script literal or the title-channel delimiter scheme.
fn is_safe_request_id(request_id: &str) -> bool {
    !request_id.is_empty()
        && request_id.len() <= 64
        && request_id.bytes().all(|b| b.is_ascii_alphanumeric())
}

fn is_safe_browser_title_chunk(request_id: &str, seq: usize, total: usize, chunk: &str) -> bool {
    total > 0
        && seq < total
        && total <= MAX_BROWSER_TITLE_CHANNEL_CHUNKS
        && chunk.len() <= MAX_BROWSER_TITLE_CHANNEL_CHUNK_CHARS
        && is_safe_request_id(request_id)
}

fn register_browser_title_request<R: tauri::Runtime>(
    app: &tauri::AppHandle<R>,
    request_id: &str,
) -> Result<(), String> {
    let state = app.state::<BrowserTitleChannels>();
    let mut channels = state
        .0
        .lock()
        .map_err(|_| "Failed to access browser title channels".to_string())?;
    channels.pending.insert(request_id.to_string());
    channels.buffers.remove(request_id);
    Ok(())
}

fn clear_browser_title_request<R: tauri::Runtime>(app: &tauri::AppHandle<R>, request_id: &str) {
    let state = app.state::<BrowserTitleChannels>();
    let Ok(mut channels) = state.0.lock() else {
        return;
    };
    channels.pending.remove(request_id);
    channels.buffers.remove(request_id);
}

fn normalize_browser_extraction_mode(mode: Option<&str>) -> Result<&'static str, String> {
    match mode.unwrap_or("auto") {
        "auto" => Ok("auto"),
        "article" => Ok("article"),
        "selection" => Ok("selection"),
        "visible" => Ok("visible"),
        "list" => Ok("list"),
        _ => Err("Invalid browser extraction mode".to_string()),
    }
}

fn schedule_browser_title_request_cleanup<R: tauri::Runtime>(
    app: tauri::AppHandle<R>,
    request_id: String,
) {
    tauri::async_runtime::spawn(async move {
        tokio::time::sleep(std::time::Duration::from_secs(30)).await;
        clear_browser_title_request(&app, &request_id);
    });
}

/// Reassemble base64 chunks streamed through `document.title` and, once
/// complete, decode and emit them to the frontend. No-op for titles that don't
/// carry the agent marker (i.e. ordinary page title changes).
fn handle_browser_title_report<R: tauri::Runtime>(
    app: &tauri::AppHandle<R>,
    label: &str,
    title: &str,
) {
    const MARKER: &str = "__AGENT__";
    let Some(rest) = title.strip_prefix(MARKER) else {
        return;
    };
    // rest = <requestId>|<seq>|<total>|<base64 chunk>
    let mut parts = rest.splitn(4, '|');
    let (Some(request_id), Some(seq), Some(total), Some(chunk)) =
        (parts.next(), parts.next(), parts.next(), parts.next())
    else {
        return;
    };
    let (Ok(seq), Ok(total)) = (seq.parse::<usize>(), total.parse::<usize>()) else {
        return;
    };
    if !is_safe_browser_title_chunk(request_id, seq, total, chunk) {
        return;
    }

    let state = app.state::<BrowserTitleChannels>();
    let Ok(mut channels) = state.0.lock() else {
        return;
    };
    if !channels.pending.contains(request_id) {
        return;
    };
    let buffer = channels
        .buffers
        .entry(request_id.to_string())
        .or_insert_with(|| TitleChannelBuffer {
            total,
            chunks: BTreeMap::new(),
        });
    buffer.total = total;
    buffer.chunks.insert(seq, chunk.to_string());
    if buffer.chunks.len() < buffer.total {
        return;
    }

    let assembled: String = buffer.chunks.values().cloned().collect();
    channels.buffers.remove(request_id);
    channels.pending.remove(request_id);
    drop(channels);

    let Ok(bytes) = base64::engine::general_purpose::STANDARD.decode(assembled.as_bytes()) else {
        return;
    };
    let Ok(payload) = String::from_utf8(bytes) else {
        return;
    };

    let _ = app.emit(
        &format!("browser-agent-data-{}", label),
        BrowserAgentData {
            request_id: request_id.to_string(),
            payload,
        },
    );
}

/// Primary report channel: the bridge invokes this directly from the external
/// webview. We resolve the originating webview's label and forward the snapshot
/// to the frontend on the same `browser-agent-data-{label}` event the title
/// channel uses, so the frontend has a single listener regardless of channel.
///
/// Currently unreachable by default: external browser webviews have no
/// capability granting them this command, so the bridge falls back to the
/// `document.title` channel (see `handle_browser_title_report`). Kept registered
/// for a future opt-in fast path behind a tightly-scoped capability.
#[allow(dead_code)]
#[tauri::command]
fn browser_report_content<R: tauri::Runtime>(
    webview: tauri::Webview<R>,
    app: tauri::AppHandle<R>,
    request_id: String,
    payload: String,
) -> Result<(), String> {
    if !is_safe_request_id(&request_id) {
        return Err("Invalid request id".to_string());
    }
    clear_browser_title_request(&app, &request_id);
    let label = webview.label().to_string();
    app.emit(
        &format!("browser-agent-data-{}", label),
        BrowserAgentData {
            request_id,
            payload,
        },
    )
    .map_err(|error| error.to_string())
}

/// Trigger snapshot collection in a browser webview by calling the injected
/// `window.__agentCollect(requestId)`. The result arrives asynchronously on
/// `browser-agent-data-{label}` (see the two report channels above).
#[tauri::command]
async fn browser_collect_content<R: tauri::Runtime>(
    app: tauri::AppHandle<R>,
    label: String,
    request_id: String,
    extraction_mode: Option<String>,
) -> Result<(), String> {
    if !is_safe_request_id(&request_id) {
        return Err("Invalid request id".to_string());
    }
    let extraction_mode = normalize_browser_extraction_mode(extraction_mode.as_deref())?;
    let extraction_mode_json =
        serde_json::to_string(extraction_mode).map_err(|error| error.to_string())?;
    if let Some(webview) = app.get_webview(&label) {
        register_browser_title_request(&app, &request_id)?;
        schedule_browser_title_request_cleanup(app.clone(), request_id.clone());
        let (tx, rx) = tokio::sync::oneshot::channel();
        let request_id_for_script = request_id.clone();
        let _ = app.run_on_main_thread(move || {
            let script = format!(
                "window.__agentCollect && window.__agentCollect('{}', {{ mode: {} }})",
                request_id_for_script, extraction_mode_json
            );
            let res = webview.eval(&script).map_err(|error| error.to_string());
            let _ = tx.send(res);
        });
        let result = rx.await.map_err(|e| format!("Channel error: {e}"))?;
        if result.is_err() {
            clear_browser_title_request(&app, &request_id);
        }
        result
    } else {
        Err(format!("Browser webview not found: {label}"))
    }
}

/// Strips a leading UTF-8 BOM (U+FEFF) if present. Windows tools (older Notepad,
/// some exporters) prefix text files with `EF BB BF`; left in place it surfaces
/// as an invisible character that breaks front-matter (`---`) and heading
/// detection in the editor. We normalize it away on read; saves never write it
/// back, matching VS Code's default.
fn strip_utf8_bom(content: String) -> String {
    match content.strip_prefix('\u{feff}') {
        Some(stripped) => stripped.to_string(),
        None => content,
    }
}

#[tauri::command]
async fn read_file(path: String) -> Result<String, String> {
    tokio::task::spawn_blocking(move || std::fs::read_to_string(path).map(strip_utf8_bom))
        .await
        .map_err(|error| format!("Failed to join file read task: {error}"))?
        .map_err(|error| error.to_string())
}

#[tauri::command]
async fn write_file(path: String, content: String) -> Result<(), String> {
    tokio::task::spawn_blocking(move || atomic_write(&path, content.as_bytes()))
        .await
        .map_err(|error| format!("Failed to join file write task: {error}"))?
        .map_err(|error| error.to_string())
}

#[tauri::command]
async fn copy_file(source_path: String, destination_path: String) -> Result<(), String> {
    tokio::task::spawn_blocking(move || -> Result<(), String> {
        ensure_parent_directory(&destination_path)?;
        std::fs::copy(&source_path, &destination_path)
            .map(|_| ())
            .map_err(|error| error.to_string())
    })
    .await
    .map_err(|error| format!("Failed to join file copy task: {error}"))?
}

/// Documents are replaced atomically (write to a sibling temp file, then
/// rename over the target) so a crash or power loss mid-write can never leave
/// the user's file truncated.
fn atomic_write(path: &str, contents: &[u8]) -> std::io::Result<()> {
    let target = Path::new(path);
    let parent = target.parent().filter(|p| !p.as_os_str().is_empty());
    if let Some(parent) = parent {
        std::fs::create_dir_all(parent)?;
    }

    let file_name = target
        .file_name()
        .map(|name| name.to_string_lossy().into_owned())
        .unwrap_or_else(|| "file".to_string());
    let unique = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|duration| duration.as_nanos())
        .unwrap_or_default();
    let temp_name = format!("{file_name}.{}.{unique}.tmp", std::process::id());
    let temp_path = match parent {
        Some(parent) => parent.join(temp_name),
        None => PathBuf::from(temp_name),
    };

    std::fs::write(&temp_path, contents)?;
    if let Err(error) = std::fs::rename(&temp_path, target) {
        let _ = std::fs::remove_file(&temp_path);
        return Err(error);
    }
    Ok(())
}

