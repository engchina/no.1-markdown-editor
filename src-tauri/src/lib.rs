/// Content-script bridge injected into every external browser webview.
const BROWSER_BRIDGE_SCRIPT: &str = include_str!("browser_bridge.js");

/// Title-channel reassembly buffers, keyed by requestId. Used as the
/// cross-platform fallback when the external webview cannot reach the Tauri IPC
/// (`browser_report_content`) directly — the bridge then streams the base64
/// payload through `document.title` in chunks.
#[derive(Default)]
struct BrowserTitleChannels(Mutex<HashMap<String, TitleChannelBuffer>>);

struct TitleChannelBuffer {
    total: usize,
    chunks: BTreeMap<usize, String>,
}

/// Payload emitted to the frontend on `browser-agent-data-{label}` once a full
/// page snapshot has been received (via either channel). `payload` is the JSON
/// string produced by the bridge's `buildSnapshot()`.
#[derive(Clone, serde::Serialize)]
#[serde(rename_all = "camelCase")]
struct BrowserAgentData {
    request_id: String,
    payload: String,
}

/// requestIds are generated by the frontend and embedded into an `eval` string;
/// restrict them to an alphanumeric allow-list so they can never break out of
/// the script literal or the title-channel delimiter scheme.
fn is_safe_request_id(request_id: &str) -> bool {
    !request_id.is_empty()
        && request_id.len() <= 64
        && request_id.bytes().all(|b| b.is_ascii_alphanumeric())
}

/// Reassemble base64 chunks streamed through `document.title` and, once
/// complete, decode and emit them to the frontend. No-op for titles that don't
/// carry the agent marker (i.e. ordinary page title changes).
fn handle_browser_title_report<R: tauri::Runtime>(
    app: &tauri::AppHandle<R>,
    label: &str,
    title: &str,
) {
    const MARKER: &str = "__AGENT__";
    let Some(rest) = title.strip_prefix(MARKER) else {
        return;
    };
    // rest = <requestId>|<seq>|<total>|<base64 chunk>
    let mut parts = rest.splitn(4, '|');
    let (Some(request_id), Some(seq), Some(total), Some(chunk)) =
        (parts.next(), parts.next(), parts.next(), parts.next())
    else {
        return;
    };
    let (Ok(seq), Ok(total)) = (seq.parse::<usize>(), total.parse::<usize>()) else {
        return;
    };
    if total == 0 || seq >= total || !is_safe_request_id(request_id) {
        return;
    }

    let state = app.state::<BrowserTitleChannels>();
    let Ok(mut map) = state.0.lock() else {
        return;
    };
    let buffer = map
        .entry(request_id.to_string())
        .or_insert_with(|| TitleChannelBuffer {
            total,
            chunks: BTreeMap::new(),
        });
    buffer.total = total;
    buffer.chunks.insert(seq, chunk.to_string());
    if buffer.chunks.len() < buffer.total {
        return;
    }

    let assembled: String = buffer.chunks.values().cloned().collect();
    map.remove(request_id);
    drop(map);

    let Ok(bytes) = base64::engine::general_purpose::STANDARD.decode(assembled.as_bytes()) else {
        return;
    };
    let Ok(payload) = String::from_utf8(bytes) else {
        return;
    };

    let _ = app.emit(
        &format!("browser-agent-data-{}", label),
        BrowserAgentData {
            request_id: request_id.to_string(),
            payload,
        },
    );
}

/// Primary report channel: the bridge invokes this directly from the external
/// webview. We resolve the originating webview's label and forward the snapshot
/// to the frontend on the same `browser-agent-data-{label}` event the title
/// channel uses, so the frontend has a single listener regardless of channel.
///
/// Currently unreachable by default: external browser webviews have no
/// capability granting them this command, so the bridge falls back to the
/// `document.title` channel (see `handle_browser_title_report`). Kept registered
/// for a future opt-in fast path behind a tightly-scoped capability.
#[allow(dead_code)]
#[tauri::command]
fn browser_report_content<R: tauri::Runtime>(
    webview: tauri::Webview<R>,
    app: tauri::AppHandle<R>,
    request_id: String,
    payload: String,
) -> Result<(), String> {
    if !is_safe_request_id(&request_id) {
        return Err("Invalid request id".to_string());
    }
    let label = webview.label().to_string();
    app.emit(
        &format!("browser-agent-data-{}", label),
        BrowserAgentData { request_id, payload },
    )
    .map_err(|error| error.to_string())
}

/// Trigger snapshot collection in a browser webview by calling the injected
/// `window.__agentCollect(requestId)`. The result arrives asynchronously on
/// `browser-agent-data-{label}` (see the two report channels above).
#[tauri::command]
async fn browser_collect_content<R: tauri::Runtime>(
    app: tauri::AppHandle<R>,
    label: String,
    request_id: String,
) -> Result<(), String> {
    if !is_safe_request_id(&request_id) {
        return Err("Invalid request id".to_string());
    }
    if let Some(webview) = app.get_webview(&label) {
        let (tx, rx) = tokio::sync::oneshot::channel();
        let _ = app.run_on_main_thread(move || {
            let script = format!(
                "window.__agentCollect && window.__agentCollect('{}')",
                request_id
            );
            let res = webview.eval(&script).map_err(|error| error.to_string());
            let _ = tx.send(res);
        });
        rx.await.map_err(|e| format!("Channel error: {e}"))?
    } else {
        Err(format!("Browser webview not found: {label}"))
    }
}

